export const STRINGS: Record<Locale, Strings> = { 'zh-cn': zh, en, ja };

/**
 * Metadata text in the best language available for `locale`: the locale's own
 * text, then English, then Chinese (Japanese pages read ja → en → zh-CN).
 * `lang` is the language actually returned, for the element's `lang` attribute.
 */
export function localizedText(text: LocalizedText, locale: Locale): { text: string; lang: 'zh-CN' | 'en' | 'ja' } {
  const order = locale === 'zh-cn' ? (['zh-CN', 'en'] as const) : locale === 'en' ? (['en', 'zh-CN'] as const) : (['ja', 'en', 'zh-CN'] as const);
  for (const lang of order) {
    const value = text[lang];
    if (value !== undefined) return { text: value, lang };
  }
  return { text: text['zh-CN'], lang: 'zh-CN' };
}

/** Human-readable byte size (binary units), e.g. `4.0 MiB`. */
export function formatBytes(size: number, locale: Locale): string {
  const units = ['B', 'KiB', 'MiB', 'GiB'];
  let value = size;
  let unit = 0;
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024;
    unit += 1;
  }
  const digits = unit === 0 ? 0 : 1;
  return `${new Intl.NumberFormat(LANG[locale], { maximumFractionDigits: digits, minimumFractionDigits: digits }).format(value)} ${units[unit]}`;
}

/** UTC date-time for footers and tables; the build time zone never leaks into output. */
export function formatUtc(time: number | string, locale: Locale, withTime = true): string {
  return new Intl.DateTimeFormat(LANG[locale], {
    dateStyle: 'medium',
    timeStyle: withTime ? 'short' : undefined,
    timeZone: 'UTC',
  }).format(new Date(time));
}

/** Share of `part` in `total` as a whole-number percentage, or `null` when there is nothing to divide. */
export function formatPercent(part: number, total: number, locale: Locale): string | null {
  if (total === 0) return null;
  return new Intl.NumberFormat(LANG[locale], { style: 'percent', maximumFractionDigits: 0 }).format(part / total);
}
